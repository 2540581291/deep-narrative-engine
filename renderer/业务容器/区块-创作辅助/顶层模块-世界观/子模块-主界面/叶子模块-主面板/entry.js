// 兵种名 → 兵种类别。查不到的一律落「步兵」（成建制武装的默认位）。
// 归类表按「这一个单位在战场上是什么」判，不按它属于哪个势力。
function 世界军队类别查(名) {
  var ks = Object.keys(世界军队归类表);
  for (var i = 0; i < ks.length; i++) {
    if (世界军队归类表[ks[i]].indexOf(名) >= 0) return ks[i];
  }
  return '步兵';
}

// 跨板块挪维度：把 旧板块·旧维度 整批挪到 新板块·新维度（仅当目标里没有同名条目）。
// 用于「维度搬过家」的历史遗留（种族·性征与繁衍 → 文化·性征与繁衍；世界设定·剧情种子 → 时间线·剧情种子）。
// 挪完删空键；返回搬了几条。**不做语义猜测的那几个维度（种族与文明 / 聚落）不在这里动**，
// 它们由界面铺成 ⚠ 旧维度 TAB 亮出来，用条目弹窗的「所属维度」手动归类。
function 世界挪维度(x, 旧板块, 旧维度, 新板块, 新维度) {
  if (!x || !x[旧板块] || !Array.isArray(x[旧板块][旧维度]) || !x[旧板块][旧维度].length) return 0;
  x[新板块] = x[新板块] || {};
  var 新 = x[新板块][新维度] = x[新板块][新维度] || [];
  var 已有 = {};
  新.forEach(function(it) { if (it && it['条目']) 已有[it['条目']] = 1; });
  var 搬 = 0;
  x[旧板块][旧维度].forEach(function(it) {
    var n = it && it['条目'];
    if (n && 已有[n]) return;   // 目标里已有同名 → 不重复搬（避免出现两条同名）
    if (n) 已有[n] = 1;
    新.push(it); 搬++;
  });
  delete x[旧板块][旧维度];
  if (!Object.keys(x[旧板块]).length) delete x[旧板块];
  return 搬;
}

// 就地迁移：改 x（content 对象）与 m（信息对象），返回 true 表示动过、需要写盘。
// 分流**不读任何白名单**——一张静态归类表 + 「查不到落步兵」的兜底就够了。
// （曾经按 信息.json 的「势力清单」把真组织挑出来单列成一个「军势」维度，那个维度已删：
//   兽群、禁卫军听起来就是兵种，该散进后面的类型里去。）
function 世界军队迁移(x, m) {
  if (!x || typeof x !== 'object') return false;
  var 旧势力 = x['势力'];
  var 旧军武 = (旧势力 && Array.isArray(旧势力['军武集团'])) ? 旧势力['军武集团'] : null;
  var 动过 = false;

  // ① content：势力 · 军武集团 → 军队
  if (旧军武 && 旧军武.length) {
    x['军队'] = x['军队'] || {};
    var 军队 = x['军队'];
    var 器 = {};

    // 逐条分流。**只处理有「条目」的条目**，原样搬过去不动内容——
    // 分类只决定它落在哪个子 TAB，条目的字段一个字不改（老条目只有 条目+详细描述，
    // 新字段留空，打开就能补，符合零锁定）。
    旧军武.forEach(function(it) {
      var n = it && it['条目'];
      // 没名字的脏条目：落「步兵」（版块表里真有的维度）。
      // 原来落的是「步兵与近战」——那个维度名早就不存在了，条目会永远隐形。
      if (!n) { (军队['步兵'] = 军队['步兵'] || []).push(it); return; }
      if (世界军队器物.indexOf(n) >= 0) { 器[n] = it; return; }
      var 类 = 世界军队类别查(n);
      军队[类] = 军队[类] || [];
      军队[类].push(it);
    });

    // 器物搬进「物品 · 器物」（物品是全量器物目录，器物是其中的杂项实用器具类）
    // **整条原样搬**：只挑 条目+详细描述 会把 所属势力 / 子级 / 历史 丢干净，
    // 那些器物就不在任何势力的关联总览里出现了。
    if (Object.keys(器).length) {
      x['物品'] = x['物品'] || {};
      x['物品']['器物'] = x['物品']['器物'] || [];
      Object.keys(器).forEach(function(k) {
        var it = 器[k];
        if (!it['条目']) it['条目'] = k;
        x['物品']['器物'].push(it);
      });
    }

    // 清空旧维度：整批都已分流到「军队」，原数组要一并清掉，
    // 否则旧键会留在盘上，下一次打开又会把同一批条目再分流一遍（重复累加）。
    旧军武.length = 0;
    delete 旧势力['军武集团'];
    if (!Object.keys(旧势力).length) delete x['势力'];
    动过 = true;
  }

  // ② 信息文件：modules 补上「军队」（旧的 7 块列表里没有它）
  if (m && Array.isArray(m.modules) && m.modules.indexOf('军队') < 0) {
    var 序 = ['世界设定', '势力', '地理', '种族', '军队', '物品', '文化', '时间线'];
    var 新 = [];
    序.forEach(function(k) {
      if (m.modules.indexOf(k) >= 0 || k === '军队') 新.push(k);
    });
    m.modules.forEach(function(k) { if (新.indexOf(k) < 0) 新.push(k); });
    m.modules = 新;
    动过 = true;
  }
  // 旧 modules 里若还写着已废弃的「军武集团」，一并抹掉
  if (m && Array.isArray(m.modules) && m.modules.indexOf('军武集团') >= 0) {
    m.modules = m.modules.filter(function(k) { return k !== '军武集团'; });
    动过 = true;
  }
  return 动过;
}

// ===== Store.world 统一挂载（主界面为唯一挂载点）=====
Store.world = Object.assign(createStore('world'), {
  // 读取世界内容（content.json）
  loadContent: function(t) {
    var sd = LocalFS.sanitize(t);
    var dir = STORE_DIRS.world + '/' + sd + '/';
    var 信路径 = dir + sd + ' - 信息.json';
    return Promise.all([LocalFS.readJSON(dir + 'content.json'), LocalFS.readJSON(信路径).catch(function() { return null; })])
      .then(function(res) {
      var x = res[0] || {};
      var m = res[1] || null;
      // 键名迁移：地理旧子维度名 → 新名（世界地理/大城名宗/乡镇村落/奇境）
      var 动过 = false;
      var geo = (x && x.地理) ? x.地理 : null;
      if (geo) {
        if (geo['地理与生态'] !== undefined && !geo['世界地理']) { geo['世界地理'] = geo['地理与生态']; delete geo['地理与生态']; 动过 = true; }
        if (geo['聚落志'] !== undefined && !geo['聚落']) { geo['聚落'] = geo['聚落志']; delete geo['聚落志']; 动过 = true; }
        if (geo['奇境录'] !== undefined && !geo['奇境']) { geo['奇境'] = geo['奇境录']; delete geo['奇境录']; 动过 = true; }
      }
      // 维度搬过家的两块：整批挪到新板块的现维度（幂等：挪完旧键就没了）
      try {
        if (世界挪维度(x, '种族', '性征与繁衍', '文化', '性征与繁衍')) 动过 = true;
        if (世界挪维度(x, '世界设定', '剧情种子', '时间线', '剧情种子')) 动过 = true;
      } catch (e) { /* 迁移失败不影响打开世界 */ }
      // 军队独立成块：把旧的「势力 · 军武集团」就地搬到顶层「军队」，并按兵种类型散开。
      // 分流只靠 entry 里的静态归类表，**不读任何白名单**。
      if (x['势力'] && Array.isArray(x['势力']['军武集团']) && x['势力']['军武集团'].length) {
        try { if (世界军队迁移(x, m)) 动过 = true; } catch (e) { /* 同上 */ }
      }
      // 迁移结果**等落盘再返回**（幂等：下回打开旧键已不在，不会再写）。
      // 必须 await，不能甩到后台写——否则用户紧接着的一次编辑可能先落盘、被这次迁移覆盖掉。
      if (!动过) return x;
      var 写 = [LocalFS.saveJSON(dir + 'content.json', x)];
      if (m) 写.push(LocalFS.saveJSON(信路径, m));
      return Promise.all(写).catch(function() { return null; }).then(function() { return x; });
    });
  },
  // 保存世界内容（content.json）
  saveContent: function(t, c) {
    var dir = STORE_DIRS.world + '/' + LocalFS.sanitize(t) + '/';
    return LocalFS.saveJSON(dir + 'content.json', c || {});
  },
});

