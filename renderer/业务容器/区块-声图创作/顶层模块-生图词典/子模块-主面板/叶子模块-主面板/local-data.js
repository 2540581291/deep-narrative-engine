// 解析 AI 返回的 seq：只认纯数字；若带了「1.」「第1」「一」等杂字符，尽力提取首个数字，实在提取不到返回 null
function stcdLocalSeqNum(v) {
  if (v == null || v === '') return null;
  if (typeof v === 'number' && isFinite(v)) return v;
  var s = String(v).trim();
  if (/^\d+$/.test(s)) return parseInt(s, 10);
  var m = s.match(/\d+/);
  if (m) return parseInt(m[0], 10);
  var cn = { '一': 1, '二': 2, '三': 3, '四': 4, '五': 5, '六': 6, '七': 7, '八': 8, '九': 9, '十': 10 };
  var first = s.charAt(0);
  if (cn[first] != null) return cn[first];
  return null;
}

// 按 AI 输出的 seq 数字序号排序（actual/imagined 各自从 1 开始；无 seq 的保持原顺序排在末尾）
function stcdLocalOptSuggestSort(items) {
  var withSeq = [];
  var withoutSeq = [];
  (items || []).forEach(function(it) {
    if (!it) return;
    var n = stcdLocalSeqNum(it.seq);
    if (n != null) withSeq.push({ it: it, n: n });
    else withoutSeq.push(it);
  });
  withSeq.sort(function(a, b) { return a.n - b.n; });
  return withSeq.map(function(x) { return x.it; }).concat(withoutSeq);
}

// 追加合并：保留原有，仅追加与已有 label 不重复的新方案（不覆盖）
function stcdLocalOptSuggestMerge(cur, fresh) {
  var seen = {};
  var out = [];
  (cur || []).forEach(function(it) {
    if (it && it.label) { seen[it.label] = true; out.push(it); }
    else if (it) out.push(it);
  });
  (fresh || []).forEach(function(it) {
    if (it && it.label && !seen[it.label]) { seen[it.label] = true; out.push(it); }
    else if (it && !it.label) out.push(it);
  });
  return out;
}

// 顺序调整：按 AI 返回的 seq 数字序号重排（按 label 匹配原方案，保留原内容；未返回的追加在末尾）
function stcdLocalOptSuggestReorder(cur, fresh) {
  var byLabel = {};
  var byTime = {};
  (cur || []).forEach(function(it) {
    if (it && it.label) byLabel[it.label] = it;
    if (it && it.time) {
      (byTime[it.time] = byTime[it.time] || []).push(it);
    }
  });
  var ordered = stcdLocalOptSuggestSort(fresh);
  var out = [];
  var used = {};
  function pick(it) {
    var lbl = it && it.label;
    if (lbl && byLabel[lbl] && !used[lbl]) { used[lbl] = true; return byLabel[lbl]; }
    // label 对不上时按 time 兜底（同时间段的多个方案按原顺序依次消耗）
    if (it && it.time && byTime[it.time]) {
      var pool = byTime[it.time].filter(function(x) { return x && x.label && !used[x.label]; });
      if (pool.length) { var hit = pool[0]; used[hit.label] = true; return hit; }
    }
    return null;
  }
  (ordered || []).forEach(function(it) {
    var hit = pick(it);
    if (hit) out.push(hit);
  });
  (cur || []).forEach(function(it) {
    if (it && it.label && !used[it.label]) { used[it.label] = true; out.push(it); }
    else if (it && !it.label) out.push(it);
  });
  return out;
}

// fillFn：合并本次返回到对应字段 → 保存 → 刷新面板
// 排序规则：以 AI 返回的 seq 数字序号为准，actual/imagined 分开各自从 1 起排序
function stcdLocalOptSuggestShow(d) {
  var ctx = STCD.localOptSuggestCtx || { key: (STCD.localCharOpt || ''), mode: 'init' };
  var key = ctx.key;
  var actual = stcdLocalOptSuggestSort((d && d.actual) || []);
  var imagined = stcdLocalOptSuggestSort((d && d.imagined) || []);
  if (!actual.length && !imagined.length) { toast('未返回方案，请重试'); return; }
  var list = stcdLocalSuggestListOf(key);
  var merged = { actual: [], imagined: [] };
  var targetSide = ctx.side || null;
  // before/after/between/refill 属「定点插入」：用户点了哪一列(targetSide)，新方案就应进那一列，并插到指定位置。
  // AI 返回的新方案可能落在 actual 或 imagined 任一组，与用户所点列不一致（AI 的分组认知 ≠ 用户列）。
  // 故对这类操作：把 AI 返回的 actual+imagined 合并，一律作为「所点列 targetSide」的新方案插入；非所点列不改动。
  var isInsertMode = (ctx.mode === 'before' || ctx.mode === 'after' || ctx.mode === 'between' || ctx.mode === 'refill');
  ['actual', 'imagined'].forEach(function(side) {
    var cur = list[side] || [];
    var fresh = side === 'actual' ? actual : imagined;
    // 定点插入：非所点列 → 保持原样；所点列 → 用"合并后的新鲜方案"插入
    if (isInsertMode) {
      if (targetSide && side !== targetSide) { merged[side] = cur; return; }
      // 所点列：合并 AI 返回的 actual+imagined 全部作为新方案（去重）
      var allFresh = actual.concat(imagined);
      var ins = (ctx.insertIndex != null) ? ctx.insertIndex : cur.length;
      var seenLabels = {};
      cur.forEach(function(it) { if (it && it.label) seenLabels[it.label] = true; });
      var newItems = allFresh.filter(function(it) { return !(it && it.label && seenLabels[it.label]); });
      merged[side] = cur.slice(0, ins).concat(newItems, cur.slice(ins));
      return;
    }
    if (targetSide && targetSide !== side) { merged[side] = cur; return; }
    if (ctx.mode === 'init' || ctx.mode === 'append') {
      // 保留原有，追加不重复的新方案（fresh 已按 seq 排序）
      merged[side] = stcdLocalOptSuggestMerge(cur, fresh);
    } else if (ctx.mode === 'reorder') {
      // 仅调整顺序，按 AI 的 seq 重排，内容不变
      merged[side] = stcdLocalOptSuggestReorder(cur, fresh);
    } else if (ctx.mode === 'between') {
      merged[side] = cur;
    } else if (ctx.mode === 'regenerate') {
      var ri = ctx.replaceIndex;
      merged[side] = (ri != null && cur[ri]) ? (fresh.length ? cur.slice(0, ri).concat(fresh, cur.slice(ri + 1)) : cur.slice()) : cur.slice();
    } else {
      merged[side] = cur;
    }
  });
  STCD.localOptSuggestList[key] = merged;
  stcdLocalSaveDetail();  // 生成结果立即持久化，导入同角色可恢复
  stcdLocalSyncTimelines();
}

// 深化设计 · 回填：按 label 定位方案，只改写 desc（其余字段不动），已选用方案同步更新，立即持久化
function stcdLocalOptDeepenShow(d) {
  var ctx = STCD.localOptDeepenCtx || {};
  var key = ctx.key || STCD.localCharOpt || 'charNormal';
  var items = (d && d.items) || [];
  if (!items.length) { toast('未返回深化内容，请重试'); return; }
  var list = stcdLocalSuggestListOf(key);
  var updated = 0;
  var notFound = [];
  items.forEach(function(it) {
    if (!it || !it.label) return;
    var desc = String(it.desc || '').trim();
    if (!desc) return;
    var hit = false;
    ['actual', 'imagined'].forEach(function(side) {
      var arr = list[side] || [];
      for (var i = 0; i < arr.length; i++) {
        if (arr[i] && arr[i].label === it.label) {
          arr[i].desc = desc;
          arr[i].deepened = true;
          hit = true;
          // 若该方案已勾选用，同步更新其 desc（localOptDetail 中是独立副本）
          if (STCD.localOptDetail && STCD.localOptDetail[key]) {
            var det = stcdLocalDetailAsList(STCD.localOptDetail[key]);
            det.forEach(function(dd) {
              if (dd && dd.label === it.label && dd.side === side) dd.desc = desc;
            });
          }
          return;
        }
      }
    });
    if (hit) updated++;
    else notFound.push(it.label);
  });
  if (!updated) { toast('未能匹配到待深化方案（label 不一致）'); return; }
  stcdLocalSaveDetail();  // 深化结果立即持久化
  stcdLocalSyncTimelines();
  toast(notFound.length ? '已深化 ' + updated + ' 条（' + notFound.length + ' 条未匹配：' + notFound.slice(0, 3).join('、') + '）' : '已深化 ' + updated + ' 条方案');
}

// 勾选/取消勾选时间线方案（单选互斥：选中新方案时清空旧选择；再点已选中项取消）
window.stcdLocalOptSuggestToggle = function(key, side, label) {
  var list = stcdLocalSuggestListOf(key);
  var arr = list[side] || [];
  var item = null;
  for (var i = 0; i < arr.length; i++) {
    if (arr[i] && arr[i].label === label) { item = arr[i]; break; }
  }
  if (!item) return;
  if (!STCD.localOptDetail) STCD.localOptDetail = {};
  var det = stcdLocalDetailAsList(STCD.localOptDetail[key]);
  var found = -1;
  for (var j = 0; j < det.length; j++) {
    if (det[j] && det[j].label === label && det[j].side === side) { found = j; break; }
  }
  if (found >= 0) {
    // 再点已选中项：取消选择（单选下即清空）
    det.splice(found, 1);
  } else {
    // 单选互斥：选中新方案时清空旧选择，只保留当前这一项
    det = [{
      label: (item.label || '').trim(),
      desc: (item.desc || '').trim(),
      reason: (item.reason || '').trim(),
      time: (item.time || '').trim(),
      field: item.field,
      side: side,
      origin: item.origin || '',
    }];
  }
  STCD.localOptDetail[key] = det;
  stcdLocalSyncTimelines();
  stcdLocalSaveDetail();  // 持久化到磁盘，导入同一角色时可恢复
};

// 单独删除某条时间线方案（从生成列表与已选用中一并移除）
window.stcdLocalOptSuggestRemoveItem = function(key, side, idx) {
  if (!confirm('删除该条时间线方案？')) return;
  var list = stcdLocalSuggestListOf(key);
  var arr = list[side] || [];
  var item = arr[idx];
  if (!item) return;
  arr.splice(idx, 1);
  // 若已选用，同步移除
  if (STCD.localOptDetail) {
    var det = stcdLocalDetailAsList(STCD.localOptDetail[key]);
    var nd = [];
    det.forEach(function(d) {
      if (!(d && d.label === item.label && d.side === side)) nd.push(d);
    });
    STCD.localOptDetail[key] = nd;
  }
  stcdLocalSyncTimelines();
  stcdLocalSaveDetail();
};

// 清空该字段的整个时间线方案（生成列表 + 已选用）
window.stcdLocalOptSuggestClearTimeline = function(key) {
  if (!confirm('清空该字段的时间线方案？')) return;
  if (STCD.localOptSuggestList) STCD.localOptSuggestList[key] = { actual: [], imagined: [] };
  if (STCD.localOptSuggestSel) STCD.localOptSuggestSel[key] = { actual: {}, imagined: {} };
  if (STCD.localOptDetail) delete STCD.localOptDetail[key];
  stcdLocalSyncTimelines();
  stcdLocalSaveDetail();
};
